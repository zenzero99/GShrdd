# Rebuilds src/data/bodies.ts from the MuscleMap body art (MIT, github.com/melihcolpan/MuscleMap).
#   git clone --depth 1 https://github.com/melihcolpan/MuscleMap /tmp/MuscleMap
#   python3 scripts/build_bodies.py /tmp/MuscleMap
# Steps (scripts/bodies): 1 extract the SVG paths from the Swift sources, 2 map muscles to our groups and reshape
# the male to a Classic Physique, 3 fit the viewBoxes. Needs: pip install svgpathtools shapely
import json, os, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__)); src = os.path.join(sys.argv[1], 'Sources/MuscleMap/Data')
work = tempfile.mkdtemp(); os.makedirs(os.path.join(work, 'mm'))
for step, args in (('1_extract.py', [src, 'mm/paths.json']), ('2_build.py', []), ('3_fit.py', [])):
    subprocess.run([sys.executable, os.path.join(here, 'bodies', step), *args], cwd=work, check=True)
B = json.load(open(os.path.join(work, 'mm/bodies.json')))
def fig(f):
    return '{\n    viewBox: %s,\n    body: [\n%s\n    ],\n    muscles: [\n%s\n    ],\n  }' % (
        json.dumps(f['viewBox']), '\n'.join(f'      {json.dumps(d)},' for d in f['body']),
        '\n'.join(f'      [{json.dumps(g)}, {json.dumps(d)}],' for g, d in f['muscles']))
ts = f"""// Generated by scripts/build_bodies.py. Do not edit by hand.
// Male and female body art adapted from MuscleMap by Melih Colpan (MIT licence, github.com/melihcolpan/MuscleMap),
// mapped to FitForge's 16 muscle groups; the male is reshaped to a Classic Physique. Full figures (no mirroring).
import type {{ GroupKey }} from './muscleModel';
import type {{ Sex }} from './profile';

export type Figure = {{ viewBox: string; body: string[]; muscles: [GroupKey, string][] }};

export const BODIES: Record<Sex, {{ front: Figure; back: Figure }}> = {{
  male: {{
    front: {fig(B['male_front'])},
    back: {fig(B['male_back'])},
  }},
  female: {{
    front: {fig(B['female_front'])},
    back: {fig(B['female_back'])},
  }},
}};
"""
open(os.path.join(here, '..', 'src/data/bodies.ts'), 'w').write(ts)
print('wrote src/data/bodies.ts')
